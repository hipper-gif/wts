-- 029: 定期点検の項目に「該当なし」を足す（ADR-0018）
-- 背景: クラッチ・点火時期・デストリビューター等、AT車・HV車に無い項目も常に出る。
--       選べるのが「良好・要注意・不良」だけで、無い項目は空のまま＝未点検と区別できなかった（全画面点検 D-26）。
-- 選択肢を1つ足すだけ（既存の値はそのまま）。
-- ============================================================

ALTER TABLE periodic_inspection_items
  MODIFY `result` enum('良好','要注意','不良','該当なし') NOT NULL;
